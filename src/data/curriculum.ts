export function levelText(level: Level, locale: "ar" | "en") {
  return locale === "ar"
    ? { name: level.nameAr, description: level.descriptionAr }
    : { name: level.nameEn, description: level.descriptionEn };
}

export function getLevel(id: string): Level | undefined {
  return levels.find((level) => level.id === id);
}

// Unit and lesson numbers are 1-based, matching the URL.
export function lessonId(level: LevelId, unit: number, lesson: number): string {
  return `${level}/${unit}/${lesson}`;
}

export function unitLessonIds(level: LevelId, unitNumber: number, unit: Unit): string[] {
  return unit.lessons.map((_, i) => lessonId(level, unitNumber, i + 1));
}

export function levelLessonIds(level: Level): string[] {
  return level.units.flatMap((unit, u) => unitLessonIds(level.id, u + 1, unit));
}

// The words of one part (0-based) and how many parts a lesson has.
export function partCount(words: Word[]): number {
  return Math.ceil(words.length / PART_SIZE);
}

export function partWords(words: Word[], part: number): Word[] {
  return words.slice(part * PART_SIZE, (part + 1) * PART_SIZE);
}

export type QuizQuestion = { word: Word; options: string[] };

// Deterministic (no randomness) so server and client render the same quiz.
export function buildQuiz(words: Word[]): QuizQuestion[] {
  return words.map((word, i) => {
    const picks = [0, 3, 7, 11].map((offset) => words[(i + offset) % words.length].ar);
    const shift = i % picks.length;
    const rotated = [...picks.slice(shift), ...picks.slice(0, shift)];
    return { word, options: [...new Set(rotated)] };
  });
}
