export type LevelId = "c1" | "b2" | "b1" | "a2" | "a1";

export type Word = {
  en: string;
  pos: "n" | "v" | "adj" | "adv";
  ar: string;
  // Only the first words of a lesson carry an example sentence so far.
  example?: string;
  exampleAr?: string;
};

export type GrammarPoint = { rule: string; example: string; exampleAr: string };

export type Grammar = {
  title: string;
  explanationAr: string;
  explanationEn: string;
  points: GrammarPoint[];
};

export type Lesson = {
  title: string;
  words: Word[];
  grammar?: Grammar;
};

export type Unit = {
  title: string;
  lessons: Lesson[];
};

export type Level = {
  id: LevelId;
  code: string;
  nameAr: string;
  nameEn: string;
  descriptionAr: string;
  descriptionEn: string;
  units: Unit[];
};

export const WORDS_PER_LESSON = 100;
// A lesson is studied and quizzed in parts of this many words.
export const PART_SIZE = 20;

